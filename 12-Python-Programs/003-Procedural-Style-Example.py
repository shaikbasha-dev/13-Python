"""
===============================================================================
                    Procedural Style Example
===============================================================================

Program Description:
--------------------
This program demonstrates the Procedural Programming style in Python.

Procedural Programming is a programming paradigm in which a program is
organized as a sequence of instructions. The statements are executed
one after another from top to bottom.

Author      : Shaik Mahaboob Basha
Repository  : 13-Python
File Name   : 03-Procedural-Style-Example.py

===============================================================================
"""

# -----------------------------------------------------------------------------
# Displaying the program title.
# -----------------------------------------------------------------------------
print("Procedural Programming Example")
# Output: Procedural Programming Example

# -----------------------------------------------------------------------------
# Creating two integer variables.
# These variables store the values that will be used for addition.
# -----------------------------------------------------------------------------
num1 = 10
# num1 stores the value 10.

num2 = 20
# num2 stores the value 20.

# -----------------------------------------------------------------------------
# Adding the values stored in num1 and num2.
# The result is stored in the variable named sum.
# -----------------------------------------------------------------------------
sum = num1 + num2
# sum stores the value 30.

# -----------------------------------------------------------------------------
# Displaying the value of the first number.
# -----------------------------------------------------------------------------
print("First Number :", num1)
# Output: First Number : 10

# -----------------------------------------------------------------------------
# Displaying the value of the second number.
# -----------------------------------------------------------------------------
print("Second Number :", num2)
# Output: Second Number : 20

# -----------------------------------------------------------------------------
# Displaying the addition result.
# -----------------------------------------------------------------------------
print("Sum =", sum)
# Output: Sum = 30

# -----------------------------------------------------------------------------
# Displaying a concluding message about procedural programming.
# -----------------------------------------------------------------------------
print("The program executed sequentially from top to bottom.")
# Output: The program executed sequentially from top to bottom.
