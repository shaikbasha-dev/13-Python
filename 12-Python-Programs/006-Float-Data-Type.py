# -----------------------------------------------------------------------------
# Creating a float variable named number1.
# The variable stores a positive decimal value.
# -----------------------------------------------------------------------------
number1 = 10.5
# number1 contains the float value 10.5.

# -----------------------------------------------------------------------------
# Creating a float variable named number2.
# The variable stores a negative decimal value.
# -----------------------------------------------------------------------------
number2 = -25.75
# number2 contains the float value -25.75.

# -----------------------------------------------------------------------------
# Creating a float variable named number3.
# The variable stores the decimal value 0.0.
# -----------------------------------------------------------------------------
number3 = 0.0
# number3 contains the float value 0.0.

# -----------------------------------------------------------------------------
# Displaying the value stored in number1.
# -----------------------------------------------------------------------------
print("Value of number1 :", number1)
# Output: Value of number1 : 10.5

# -----------------------------------------------------------------------------
# Displaying the value stored in number2.
# -----------------------------------------------------------------------------
print("Value of number2 :", number2)
# Output: Value of number2 : -25.75

# -----------------------------------------------------------------------------
# Displaying the value stored in number3.
# -----------------------------------------------------------------------------
print("Value of number3 :", number3)
# Output: Value of number3 : 0.0

# -----------------------------------------------------------------------------
# Displaying the data type of number1.
# type() is a built-in function used to identify the data type of a variable.
# -----------------------------------------------------------------------------
print("Data Type of number1 :", type(number1))
# Output: Data Type of number1 : <class 'float'>

# -----------------------------------------------------------------------------
# Displaying the data type of number2.
# -----------------------------------------------------------------------------
print("Data Type of number2 :", type(number2))
# Output: Data Type of number2 : <class 'float'>

# -----------------------------------------------------------------------------
# Displaying the data type of number3.
# -----------------------------------------------------------------------------
print("Data Type of number3 :", type(number3))
# Output: Data Type of number3 : <class 'float'>
