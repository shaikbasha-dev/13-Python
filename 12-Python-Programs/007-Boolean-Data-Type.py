# -----------------------------------------------------------------------------
# Creating a Boolean variable named status1.
# The variable stores the Boolean value True.
# -----------------------------------------------------------------------------
status1 = True
# status1 contains the Boolean value True.

# -----------------------------------------------------------------------------
# Creating a Boolean variable named status2.
# The variable stores the Boolean value False.
# -----------------------------------------------------------------------------
status2 = False
# status2 contains the Boolean value False.

# -----------------------------------------------------------------------------
# Displaying the value stored in status1.
# -----------------------------------------------------------------------------
print("Value of status1 :", status1)
# Output: Value of status1 : True

# -----------------------------------------------------------------------------
# Displaying the value stored in status2.
# -----------------------------------------------------------------------------
print("Value of status2 :", status2)
# Output: Value of status2 : False

# -----------------------------------------------------------------------------
# Displaying the data type of status1.
# type() is a built-in function used to identify the data type of a variable.
# -----------------------------------------------------------------------------
print("Data Type of status1 :", type(status1))
# Output: Data Type of status1 : <class 'bool'>

# -----------------------------------------------------------------------------
# Displaying the data type of status2.
# -----------------------------------------------------------------------------
print("Data Type of status2 :", type(status2))
# Output: Data Type of status2 : <class 'bool'>
