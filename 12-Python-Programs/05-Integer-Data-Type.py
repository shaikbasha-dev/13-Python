# -----------------------------------------------------------------------------
# Creating an integer variable named number1.
# The variable stores a positive integer value.
# -----------------------------------------------------------------------------
number1 = 100
# number1 contains the integer value 100.

# -----------------------------------------------------------------------------
# Creating an integer variable named number2.
# The variable stores a negative integer value.
# -----------------------------------------------------------------------------
number2 = -50
# number2 contains the integer value -50.

# -----------------------------------------------------------------------------
# Creating an integer variable named number3.
# The variable stores the value zero.
# -----------------------------------------------------------------------------
number3 = 0
# number3 contains the integer value 0.

# -----------------------------------------------------------------------------
# Displaying the value stored in number1.
# -----------------------------------------------------------------------------
print("Value of number1 :", number1)
# Output: Value of number1 : 100

# -----------------------------------------------------------------------------
# Displaying the value stored in number2.
# -----------------------------------------------------------------------------
print("Value of number2 :", number2)
# Output: Value of number2 : -50

# -----------------------------------------------------------------------------
# Displaying the value stored in number3.
# -----------------------------------------------------------------------------
print("Value of number3 :", number3)
# Output: Value of number3 : 0

# -----------------------------------------------------------------------------
# Displaying the data type of number1.
# type() is a built-in function that returns the data type of a variable.
# -----------------------------------------------------------------------------
print("Data Type of number1 :", type(number1))
# Output: Data Type of number1 : <class 'int'>

# -----------------------------------------------------------------------------
# Displaying the data type of number2.
# -----------------------------------------------------------------------------
print("Data Type of number2 :", type(number2))
# Output: Data Type of number2 : <class 'int'>

# -----------------------------------------------------------------------------
# Displaying the data type of number3.
# -----------------------------------------------------------------------------
print("Data Type of number3 :", type(number3))
# Output: Data Type of number3 : <class 'int'>
