# -----------------------------------------------------------------------------
# Creating a string variable named student_name.
# The variable stores the name of a student.
# -----------------------------------------------------------------------------
student_name = "Shaik Mahaboob Basha"
# student_name contains the string "Shaik Mahaboob Basha".

# -----------------------------------------------------------------------------
# Creating a string variable named course.
# The variable stores the course name.
# -----------------------------------------------------------------------------
course = "Python Programming"
# course contains the string "Python Programming".

# -----------------------------------------------------------------------------
# Creating a string variable named college.
# The variable stores the college name.
# -----------------------------------------------------------------------------
college = "XYZ Engineering College"
# college contains the string "XYZ Engineering College".

# -----------------------------------------------------------------------------
# Displaying the value stored in student_name.
# -----------------------------------------------------------------------------
print("Student Name :", student_name)
# Output: Student Name : Shaik Mahaboob Basha

# -----------------------------------------------------------------------------
# Displaying the value stored in course.
# -----------------------------------------------------------------------------
print("Course :", course)
# Output: Course : Python Programming

# -----------------------------------------------------------------------------
# Displaying the value stored in college.
# -----------------------------------------------------------------------------
print("College :", college)
# Output: College : XYZ Engineering College

# -----------------------------------------------------------------------------
# Displaying the data type of student_name.
# type() is a built-in function used to identify the data type of a variable.
# -----------------------------------------------------------------------------
print("Data Type of student_name :", type(student_name))
# Output: Data Type of student_name : <class 'str'>

# -----------------------------------------------------------------------------
# Displaying the data type of course.
# -----------------------------------------------------------------------------
print("Data Type of course :", type(course))
# Output: Data Type of course : <class 'str'>

# -----------------------------------------------------------------------------
# Displaying the data type of college.
# -----------------------------------------------------------------------------
print("Data Type of college :", type(college))
# Output: Data Type of college : <class 'str'>
