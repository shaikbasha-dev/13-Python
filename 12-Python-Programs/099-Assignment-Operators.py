"""
===============================================================================
File Name    : 99-Assignment-Operators.py
Description  : Assignment Operators in Python
Author       : Shaik Mahaboob Basha
===============================================================================

Definition:
Assignment operators are used to assign values to variables. They can also
perform arithmetic operations and update the variable in a single statement.

Assignment Operators:
1. =   (Assignment)
2. +=  (Add and Assign)
3. -=  (Subtract and Assign)
4. *=  (Multiply and Assign)
5. /=  (Divide and Assign)
6. //= (Floor Divide and Assign)
7. %=  (Modulus and Assign)
8. **= (Exponentiation and Assign)

Syntax:
variable operator= value

Example:
number += 5
"""

# -----------------------------------------------------------------------------
# Assigning an initial value to the variable.
# -----------------------------------------------------------------------------
number = 20

# -----------------------------------------------------------------------------
# Displaying the initial value.
# -----------------------------------------------------------------------------
print("Initial Value :", number)
# Output:
# Initial Value : 20

print()

# -----------------------------------------------------------------------------
# Using the assignment (=) operator.
# -----------------------------------------------------------------------------
number = 30

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '='  :", number)
# Output:
# After '='  : 30

# -----------------------------------------------------------------------------
# Using the add and assign (+=) operator.
# -----------------------------------------------------------------------------
number += 10

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '+=' :", number)
# Output:
# After '+=' : 40

# -----------------------------------------------------------------------------
# Using the subtract and assign (-=) operator.
# -----------------------------------------------------------------------------
number -= 5

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '-=' :", number)
# Output:
# After '-=' : 35

# -----------------------------------------------------------------------------
# Using the multiply and assign (*=) operator.
# -----------------------------------------------------------------------------
number *= 2

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '*=' :", number)
# Output:
# After '*=' : 70

# -----------------------------------------------------------------------------
# Using the divide and assign (/=) operator.
# -----------------------------------------------------------------------------
number /= 7

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '/=' :", number)
# Output:
# After '/=' : 10.0

# -----------------------------------------------------------------------------
# Using the floor divide and assign (//=) operator.
# -----------------------------------------------------------------------------
number //= 3

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '//=' :", number)
# Output:
# After '//=' : 3.0

# -----------------------------------------------------------------------------
# Using the modulus and assign (%=) operator.
# -----------------------------------------------------------------------------
number %= 2

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '%=' :", number)
# Output:
# After '%=' : 1.0

# -----------------------------------------------------------------------------
# Assigning a new value for exponentiation.
# -----------------------------------------------------------------------------
number = 5

# -----------------------------------------------------------------------------
# Using the exponentiation and assign (**=) operator.
# -----------------------------------------------------------------------------
number **= 3

# -----------------------------------------------------------------------------
# Displaying the updated value.
# -----------------------------------------------------------------------------
print("After '**=' :", number)
# Output:
# After '**=' : 125
