# -----------------------------------------------------------------------------
# Assigning hard-coded values to two variables.
# -----------------------------------------------------------------------------
number1 = 20
number2 = 5
# number1 = 20
# number2 = 5

# -----------------------------------------------------------------------------
# Displaying the input values.
# -----------------------------------------------------------------------------
print("First Number  :", number1)
print("Second Number :", number2)
# Output:
# First Number  : 20
# Second Number : 5

# -----------------------------------------------------------------------------
# Performing addition.
# -----------------------------------------------------------------------------
print("Addition        :", number1 + number2)
# Output: Addition        : 25

# -----------------------------------------------------------------------------
# Performing subtraction.
# -----------------------------------------------------------------------------
print("Subtraction     :", number1 - number2)
# Output: Subtraction     : 15

# -----------------------------------------------------------------------------
# Performing multiplication.
# -----------------------------------------------------------------------------
print("Multiplication  :", number1 * number2)
# Output: Multiplication  : 100

# -----------------------------------------------------------------------------
# Performing division.
# -----------------------------------------------------------------------------
print("Division        :", number1 / number2)
# Output: Division        : 4.0

# -----------------------------------------------------------------------------
# Performing modulus operation.
# -----------------------------------------------------------------------------
print("Modulus         :", number1 % number2)
# Output: Modulus         : 0

# -----------------------------------------------------------------------------
# Performing floor division.
# -----------------------------------------------------------------------------
print("Floor Division  :", number1 // number2)
# Output: Floor Division  : 4

# -----------------------------------------------------------------------------
# Performing exponentiation.
# -----------------------------------------------------------------------------
print("Exponentiation  :", number1 ** number2)
# Output: Exponentiation  : 3200000

# -----------------------------------------------------------------------------
# Displaying a completion message.
# -----------------------------------------------------------------------------
print("Program Completed.")
# Output:
# Program Completed.
